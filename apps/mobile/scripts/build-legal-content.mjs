// Builds src/features/settings/legalContent.ts from the legal texts in docs/legal/*.md,
// so the app shows exactly what the lawyer-reviewed Markdown says (one source of truth).
//
//   node scripts/build-legal-content.mjs        (run from apps/mobile after editing docs/legal)
//
// Understands what those files use: # / ## / ### headings, paragraphs, "- " bullets, "1. " lists,
// "> " notes, **bold**, and pipe tables. A table row becomes a small block (first cell as its title,
// the other cells as "Header: value") because a four-column table does not fit a phone.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const legalDir = join(here, '..', '..', '..', 'docs', 'legal');
const outFile = join(here, '..', 'src', 'features', 'settings', 'legalContent.ts');

const DOCS = {
  privacy: 'chinh-sach-quyen-rieng-tu.md',
  terms: 'dieu-khoan-su-dung.md',
  community: 'tieu-chuan-cong-dong.md',
};

/** "a **b** c" -> [{ text: 'a ' }, { text: 'b', bold: true }, { text: ' c' }] */
function spans(text) {
  const out = [];
  // Links to the other documents keep their words only: the app opens them from Settings.
  const plain = text.replace(/`([^`]+)`/g, '$1').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1');
  const parts = plain.split(/\*\*/);
  parts.forEach((part, i) => {
    if (part) out.push(i % 2 ? { text: part, bold: true } : { text: part });
  });
  return out.length ? out : [{ text: '' }];
}

const cells = (line) => line.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim());

function parse(markdown) {
  const lines = markdown.replace(/\r/g, '').split('\n');
  const blocks = [];
  let title = '';
  let para = [];
  const flush = () => {
    if (para.length) blocks.push({ type: 'p', spans: spans(para.join(' ')) });
    para = [];
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const trimmed = line.trim();
    if (!trimmed || /^-{3,}$/.test(trimmed)) { flush(); continue; }
    let m;
    if ((m = /^# (.+)/.exec(trimmed))) { flush(); title = m[1]; continue; }
    if ((m = /^## (.+)/.exec(trimmed))) { flush(); blocks.push({ type: 'h2', text: m[1] }); continue; }
    if ((m = /^#{3,} (.+)/.exec(trimmed))) { flush(); blocks.push({ type: 'h3', text: m[1] }); continue; }
    if (trimmed.startsWith('|')) {
      flush();
      const header = cells(trimmed);
      i += 1; // the |---|---| separator
      while (i + 1 < lines.length && lines[i + 1].trim().startsWith('|')) {
        i += 1;
        const row = cells(lines[i]);
        blocks.push({
          type: 'row',
          title: spans(row[0] ?? ''),
          fields: row.slice(1).map((value, k) => ({ label: header[k + 1] ?? '', spans: spans(value) })),
        });
      }
      continue;
    }
    if ((m = /^\s*[-*] (.+)/.exec(line))) {
      flush();
      blocks.push({ type: 'li', depth: line.search(/\S/) >= 2 ? 1 : 0, spans: spans(m[1]) });
      continue;
    }
    if ((m = /^\s*(\d+)\. (.+)/.exec(line))) {
      flush();
      blocks.push({ type: 'ol', n: Number(m[1]), spans: spans(m[2]) });
      continue;
    }
    if ((m = /^> ?(.*)/.exec(trimmed))) { flush(); blocks.push({ type: 'note', spans: spans(m[1]) }); continue; }
    // "**Label:** value" lines (the header block, contact details) each stay on their own line.
    if (/^\*\*[^*]+:\*\*/.test(trimmed)) flush();
    para.push(trimmed);
  }
  flush();
  if (!title) throw new Error('missing "# " title');
  return { title, blocks };
}

const docs = {};
for (const [key, file] of Object.entries(DOCS)) {
  docs[key] = parse(readFileSync(join(legalDir, file), 'utf8'));
  if (docs[key].blocks.length < 10) throw new Error(`${file}: only ${docs[key].blocks.length} blocks parsed`);
}

const banner = `// GENERATED by scripts/build-legal-content.mjs from docs/legal/*.md. Do not edit by hand:
// edit the Markdown, then run \`node scripts/build-legal-content.mjs\` in apps/mobile.
`;
const types = `
export type LegalSpan = { bold?: boolean; text: string };
export type LegalBlock =
  | { type: 'h2' | 'h3'; text: string }
  | { type: 'p' | 'note'; spans: LegalSpan[] }
  | { type: 'li'; depth: number; spans: LegalSpan[] }
  | { type: 'ol'; n: number; spans: LegalSpan[] }
  | { type: 'row'; title: LegalSpan[]; fields: { label: string; spans: LegalSpan[] }[] };
export type LegalDocKey = ${Object.keys(DOCS).map((k) => `'${k}'`).join(' | ')};
export type LegalDoc = { blocks: LegalBlock[]; title: string };
`;
writeFileSync(outFile, `${banner}${types}\nexport const LEGAL_DOCS: Record<LegalDocKey, LegalDoc> = ${JSON.stringify(docs, null, 1)};\n`);
console.log(Object.entries(docs).map(([k, d]) => `${k}: ${d.blocks.length} blocks`).join(', '), '->', outFile);
